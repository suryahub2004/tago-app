class HealthReportScreen extends ConsumerStatefulWidget {
  const HealthReportScreen({super.key});
  @override
  ConsumerState<HealthReportScreen> createState() => _HealthReportScreenState();
}

class _HealthReportScreenState extends ConsumerState<HealthReportScreen>
    with SingleTickerProviderStateMixin {
  late TabController _tabController;

  @override
  void initState() {
    super.initState();
    _tabController = TabController(length: 2, vsync: this);
  }

  @override
  void dispose() {
    _tabController.dispose();
    super.dispose();
  }

  // ── PDF export ──────────────────────────────────────────────────────────

  Future<void> _exportPdf(Map<String, dynamic> report, String period) async {
    final bytes = await _buildPdf(report, period);
    final name =
        'smartvital_${period}_report_${DateFormat('yyyyMMdd').format(DateTime.now())}.pdf';
    try {
      final dir = await getTemporaryDirectory();
      final file = File('${dir.path}/$name');
      await file.writeAsBytes(bytes);
      await SharePlus.instance.share(
        ShareParams(files: [XFile(file.path, mimeType: 'application/pdf')],
            subject: 'SmartVital $period Health Report'),
      );
    } catch (_) {
      await Printing.sharePdf(bytes: bytes, filename: name);
    }
  }

  Future<Uint8List> _buildPdf(Map<String, dynamic> report, String period) async {
    final doc = pw.Document();
    final m = report['metrics'] as Map<String, dynamic>? ?? {};
    final label = report['label'] as String? ?? period;
    final generated = report['generatedAt'] as String?;
    final dateStr = generated != null
        ? DateFormat('MMM d, yyyy  HH:mm').format(DateTime.parse(generated).toLocal())
        : DateFormat('MMM d, yyyy').format(DateTime.now());

    doc.addPage(pw.Page(
      pageFormat: PdfPageFormat.a4,
      margin: const pw.EdgeInsets.all(36),
      build: (pw.Context ctx) => pw.Column(
        crossAxisAlignment: pw.CrossAxisAlignment.start,
        children: [
          pw.Row(mainAxisAlignment: pw.MainAxisAlignment.spaceBetween, children: [
            pw.Column(crossAxisAlignment: pw.CrossAxisAlignment.start, children: [
              pw.Text('SmartVital',
                  style: pw.TextStyle(fontSize: 22, fontWeight: pw.FontWeight.bold)),
              pw.Text('$label Health Report',
                  style: const pw.TextStyle(fontSize: 14)),
            ]),
            pw.Text(dateStr,
                style: const pw.TextStyle(fontSize: 10, color: PdfColors.grey600)),
          ]),
          pw.Divider(thickness: 1, color: PdfColors.grey300),
          pw.SizedBox(height: 16),
          pw.Wrap(spacing: 16, runSpacing: 16, children: [
            _pdfTile('Avg Heart Rate', '${m['avgHeartRate'] ?? '--'} bpm'),
            _pdfTile('Avg HRV',       '${m['avgHrv'] ?? '--'} ms'),
            _pdfTile('SpO2',           '${m['avgSpo2'] ?? '--'} %'),
            _pdfTile('Total Steps',   _fmt(m['totalSteps'])),
            _pdfTile('Step Goal',     '${m['stepGoalPct'] ?? 0}%'),
            _pdfTile('Calories',      '${_fmt(m['totalCalories'])} kcal'),
            _pdfTile('Sleep Score',   '${m['sleepScore'] ?? '--'}'),
            _pdfTile('Avg Stress',    '${m['avgStress'] ?? '--'}'),
            _pdfTile('HRV Trend',
                '${(m['hrvTrend'] as num?)?.toStringAsFixed(1) ?? '0'} ms'),
          ]),
          pw.SizedBox(height: 24),
          pw.Divider(thickness: 0.5, color: PdfColors.grey300),
          pw.SizedBox(height: 8),
          pw.Text('Generated by SmartVital · Data sourced from wearable device',
              style: const pw.TextStyle(fontSize: 8, color: PdfColors.grey500)),
        ],
      ),
    ));
    return doc.save();
  }

  pw.Widget _pdfTile(String label, String value) => pw.Container(
        width: 150,
        padding: const pw.EdgeInsets.all(12),
        decoration: pw.BoxDecoration(
          border: pw.Border.all(color: PdfColors.grey300),
          borderRadius: pw.BorderRadius.circular(8),
        ),
        child: pw.Column(crossAxisAlignment: pw.CrossAxisAlignment.start, children: [
          pw.Text(label,
              style: const pw.TextStyle(fontSize: 9, color: PdfColors.grey600)),
          pw.SizedBox(height: 4),
          pw.Text(value,
              style: pw.TextStyle(fontSize: 15, fontWeight: pw.FontWeight.bold)),
        ]),
      );

  String _fmt(dynamic v) {
    if (v == null) return '--';
    final n = num.tryParse(v.toString());
    if (n == null) return '--';
    return NumberFormat.compact().format(n);
  }

  // ── Build ───────────────────────────────────────────────────────────────

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      backgroundColor: AppColors.background,
      appBar: AppBar(
        title: const Text('Health Reports'),
        backgroundColor: Colors.transparent,
        bottom: TabBar(
          controller: _tabController,
          indicatorColor: AppColors.primary,
          labelColor: AppColors.primary,
          unselectedLabelColor: AppColors.textSecondary,
          tabs: const [Tab(text: 'Daily'), Tab(text: 'Weekly')],
        ),
      ),
      body: TabBarView(
        controller: _tabController,
        children: [
          _ReportTab(period: 'daily', onExport: _exportPdf),
          _ReportTab(period: 'weekly', onExport: _exportPdf),
        ],
      ),
    );
  }
}

// ── Stateless tab ────────────────────────────────────────────────────────────

class _ReportTab extends ConsumerWidget {
  const _ReportTab({required this.period, required this.onExport});
  final String period;
  final Future<void> Function(Map<String, dynamic>, String) onExport;

  @override
  Widget build(BuildContext context, WidgetRef ref) {
    final reportAsync = period == 'daily'
        ? ref.watch(dailyReportProvider)
        : ref.watch(weeklyReportProvider);

    return reportAsync.when(
      loading: () => const Center(child: SvLoading()),
      error: (e, _) => Center(
        child: Padding(
          padding: const EdgeInsets.all(24),
          child: Column(
            mainAxisAlignment: MainAxisAlignment.center,
            children: [
              const Icon(Icons.error_outline, color: AppColors.danger, size: 48),
              const SizedBox(height: 12),
              Text(
                'Could not load $period report.\n${e.toString().replaceFirst("Exception: ", "")}',
                textAlign: TextAlign.center,
                style: const TextStyle(color: AppColors.textSecondary),
              ),
              const SizedBox(height: 16),
              ElevatedButton(
                onPressed: () => period == 'daily'
                    ? ref.invalidate(dailyReportProvider)
                    : ref.invalidate(weeklyReportProvider),
                child: const Text('Retry'),
              ),
            ],
          ),
        ),
      ),
      data: (report) => _ReportContent(report: report, period: period, onExport: onExport),
    );
  }
}

class _ReportContent extends StatelessWidget {
  const _ReportContent({
    required this.report,
    required this.period,
    required this.onExport,
  });
  final Map<String, dynamic> report;
  final String period;
  final Future<void> Function(Map<String, dynamic>, String) onExport;

  String _fmt(dynamic v) {
    if (v == null) return '--';
    final n = num.tryParse(v.toString());
    if (n == null) return '--';
    return NumberFormat.compact().format(n);
  }

  @override
  Widget build(BuildContext context) {
    final m = report['metrics'] as Map<String, dynamic>? ?? {};
    final label = report['label'] as String? ?? period;
    final generated = report['generatedAt'] as String?;
    final dateStr = generated != null
        ? DateFormat('MMM d, yyyy  HH:mm').format(DateTime.parse(generated).toLocal())
        : '';
    final stepGoalPct = (m['stepGoalPct'] as num?)?.toInt() ?? 0;
    final trend = (m['hrvTrend'] as num?)?.toDouble() ?? 0.0;
    final isPositive = trend >= 0;
    final trendColor = isPositive ? AppColors.success : AppColors.danger;

    return SingleChildScrollView(
      padding: const EdgeInsets.all(AppSpacing.lg),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.stretch,
        children: [
          Row(
            mainAxisAlignment: MainAxisAlignment.spaceBetween,
            children: [
              Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
                Text('$label Report',
                    style: const TextStyle(
                        fontSize: 20, fontWeight: FontWeight.w900,
                        color: AppColors.textPrimary, letterSpacing: -0.4)),
                if (dateStr.isNotEmpty)
                  Text(dateStr,
                      style: const TextStyle(
                          fontSize: 12, color: AppColors.textSecondary)),
              ]),
              FilledButton.icon(
                icon: const Icon(Icons.share_rounded, size: 16),
                label: const Text('Export PDF'),
                style: FilledButton.styleFrom(
                  backgroundColor: AppColors.primary,
                  padding: const EdgeInsets.symmetric(horizontal: 16, vertical: 10),
                  shape: RoundedRectangleBorder(
                      borderRadius: BorderRadius.circular(12)),
                ),
                onPressed: () => onExport(report, period),
              ),
            ],
          ),
          const SizedBox(height: 20),

          // Step goal
          _progressCard(
            label: 'Step Goal Achievement',
            value: '$stepGoalPct%',
            progress: stepGoalPct / 100.0,
            color: stepGoalPct >= 80 ? AppColors.success
                : stepGoalPct >= 50 ? AppColors.warning : AppColors.danger,
            subtitle: '${_fmt(m['totalSteps'])} of ${_fmt(m['stepGoal'])} steps',
          ),
          const SizedBox(height: AppSpacing.md),

          // Grid
          GridView.count(
            crossAxisCount: 2, crossAxisSpacing: 12, mainAxisSpacing: 12,
            childAspectRatio: 1.5, shrinkWrap: true,
            physics: const NeverScrollableScrollPhysics(),
            children: [
              _tile('Avg Heart Rate', '${m['avgHeartRate'] ?? '--'}', 'bpm',
                  AppColors.heartRate, Icons.favorite_rounded),
              _tile('Avg HRV', '${m['avgHrv'] ?? '--'}', 'ms',
                  AppColors.hrv, Icons.monitor_heart_rounded),
              _tile('SpO2', '${m['avgSpo2'] ?? '--'}', '%',
                  AppColors.spo2, Icons.water_drop_rounded),
              _tile('Sleep Score', '${m['sleepScore'] ?? '--'}', '/100',
                  AppColors.sleep, Icons.bedtime_rounded),
              _tile('Calories', _fmt(m['totalCalories']), 'kcal',
                  const Color(0xFFFBBF24), Icons.local_fire_department_rounded),
              _tile('Avg Stress', '${m['avgStress'] ?? '--'}', '',
                  AppColors.stress, Icons.psychology_rounded),
            ],
          ),
          const SizedBox(height: AppSpacing.md),

          // HRV trend card
          Container(
            padding: const EdgeInsets.all(16),
            decoration: BoxDecoration(
              color: trendColor.withValues(alpha: 0.06),
              borderRadius: BorderRadius.circular(16),
              border: Border.all(color: trendColor.withValues(alpha: 0.3), width: 1),
            ),
            child: Row(children: [
              Icon(isPositive ? Icons.trending_up_rounded : Icons.trending_down_rounded,
                  color: trendColor, size: 28),
              const SizedBox(width: 14),
              Expanded(child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
                const Text('HRV Trend (7-day)',
                    style: TextStyle(fontWeight: FontWeight.w700,
                        color: AppColors.textPrimary, fontSize: 13)),
                const SizedBox(height: 4),
                Text(
                  isPositive
                      ? 'HRV improving (+${trend.toStringAsFixed(1)} ms) — recovery on track.'
                      : 'HRV declining (${trend.toStringAsFixed(1)} ms) — prioritise rest.',
                  style: TextStyle(color: trendColor, fontSize: 12, height: 1.4),
                ),
              ])),
            ]),
          ),
          const SizedBox(height: 80),
        ],
      ),
    );
  }

  Widget _progressCard({
    required String label, required String value,
    required double progress, required Color color, required String subtitle,
  }) => Container(
        padding: const EdgeInsets.all(16),
        decoration: BoxDecoration(
          color: AppColors.surface, borderRadius: BorderRadius.circular(16),
          border: Border.all(color: AppColors.border, width: 0.5),
        ),
        child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
          Row(mainAxisAlignment: MainAxisAlignment.spaceBetween, children: [
            Text(label, style: const TextStyle(fontWeight: FontWeight.w700,
                color: AppColors.textPrimary)),
            Text(value, style: TextStyle(fontWeight: FontWeight.w900,
                fontSize: 18, color: color)),
          ]),
          const SizedBox(height: 10),
          ClipRRect(
            borderRadius: BorderRadius.circular(4),
            child: LinearProgressIndicator(
              value: progress.clamp(0.0, 1.0), minHeight: 8,
              color: color, backgroundColor: color.withValues(alpha: 0.12),
            ),
          ),
          const SizedBox(height: 6),
          Text(subtitle, style: const TextStyle(fontSize: 12, color: AppColors.textSecondary)),
        ]),
      );

  Widget _tile(String label, String value, String unit, Color color, IconData icon) =>
      Container(
        padding: const EdgeInsets.all(14),
        decoration: BoxDecoration(
          color: AppColors.surface, borderRadius: BorderRadius.circular(14),
          border: Border.all(color: AppColors.border, width: 0.5),
        ),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          mainAxisAlignment: MainAxisAlignment.spaceBetween,
          children: [
            Icon(icon, color: color, size: 18),
            Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
              Row(crossAxisAlignment: CrossAxisAlignment.baseline,
                  textBaseline: TextBaseline.alphabetic, children: [
                Text(value, style: TextStyle(fontSize: 22,
                    fontWeight: FontWeight.w900, color: color)),
                if (unit.isNotEmpty) ...[
                  const SizedBox(width: 2),
                  Text(unit, style: const TextStyle(fontSize: 11,
                      color: AppColors.textSecondary)),
                ],
              ]),
              Text(label, style: const TextStyle(fontSize: 11,
                  color: AppColors.textSecondary)),
            ]),
          ],
        ),
      );
}
